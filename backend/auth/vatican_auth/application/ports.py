from contextlib import AbstractAsyncContextManager
from datetime import datetime, timedelta
from types import TracebackType
from typing import Protocol
from uuid import UUID

from .models import (AccountRecord, AttemptRecord, AuditRecord, CredentialsRecord, GuestRecord,
                     PasswordCheck, PermissionRecord, RoleRecord, SessionRecord)


class Clock(Protocol):
    def now(self) -> datetime: ...


class PasswordService(Protocol):
    async def hash(self, password: str) -> str: ...
    async def verify(self, password: str, encoded_hash: str | None) -> PasswordCheck: ...


class TokenService(Protocol):
    def generate(self) -> str: ...
    def digest(self, token: str) -> bytes: ...
    def key_hash(self, key: str) -> bytes: ...


class AccountsRepository(Protocol):
    async def get(self, account_id: UUID, *, lock: bool = False) -> AccountRecord | None: ...
    async def create(self, account_id: UUID) -> None: ...


class CredentialsRepository(Protocol):
    async def lock_login(self, login: str) -> None: ...
    async def by_login(self, login: str) -> CredentialsRecord | None: ...
    async def by_account(self, account_id: UUID) -> CredentialsRecord | None: ...
    async def create(self, account_id: UUID, login: str, password_hash: str, recovery_hash: bytes) -> None: ...
    async def update(self, account_id: UUID, password_hash: str, recovery_hash: bytes, now: datetime) -> None: ...
    async def rehash(self, account_id: UUID, password_hash: str, now: datetime) -> None: ...


class GuestsRepository(Protocol):
    async def get(self, token_hash: bytes) -> GuestRecord | None: ...
    async def create(self, account_id: UUID, token_hash: bytes, expires_at: datetime) -> None: ...
    async def delete(self, account_id: UUID, token_hash: bytes | None = None) -> None: ...


class SessionsRepository(Protocol):
    async def by_access(self, token_hash: bytes) -> SessionRecord | None: ...
    async def by_refresh(self, token_hash: bytes, *, lock: bool = False) -> SessionRecord | None: ...
    async def create(self, session_id: UUID, account_id: UUID, access_hash: bytes, refresh_hash: bytes,
                     access_expires_at: datetime, refresh_expires_at: datetime) -> None: ...
    async def revoke(self, account_id: UUID, now: datetime, session_id: UUID | None = None) -> None: ...


class AttemptsRepository(Protocol):
    async def record(self, key_hash: bytes, now: datetime, window: timedelta) -> AttemptRecord: ...


class AccessRepository(Protocol):
    async def lock(self) -> None: ...
    async def roles_for(self, account_id: UUID) -> tuple[str, ...]: ...
    async def permissions_for(self, account_id: UUID) -> tuple[str, ...]: ...
    async def roles(self) -> list[RoleRecord]: ...
    async def role(self, role_id: int) -> RoleRecord | None: ...
    async def role_by_code(self, code: str) -> RoleRecord | None: ...
    async def permissions(self) -> list[PermissionRecord]: ...
    async def create_role(self, code: str, description: str, permission_codes: tuple[str, ...], assignable: bool) -> RoleRecord: ...
    async def update_role(self, role_id: int, description: str, permission_codes: tuple[str, ...], assignable: bool) -> RoleRecord: ...
    async def create_permission(self, code: str, description: str) -> PermissionRecord: ...
    async def include_permission_in_roles(self, permission_id: int, role_ids: tuple[int, ...]) -> None: ...
    async def ensure_permission(self, code: str, description: str) -> PermissionRecord: ...
    async def ensure_role(self, code: str, description: str, is_assignable: bool) -> RoleRecord: ...
    async def set_role_permissions(self, role_id: int, codes: tuple[str, ...]) -> None: ...
    async def grant(self, account_id: UUID, role_id: int, actor_id: UUID | None) -> bool: ...
    async def revoke(self, account_id: UUID, role_id: int, now: datetime) -> bool: ...
    async def has_role(self, account_id: UUID, role_id: int) -> bool: ...
    async def active_role_account_count(self, role_id: int, account_status: str) -> int: ...


class AuditRepository(Protocol):
    async def append(self, actor_id: UUID | None, target_id: UUID | None, action: str,
                     result: str, details: dict) -> None: ...
    async def list(self, limit: int, offset: int) -> list[AuditRecord]: ...


class AuthUnitOfWork(Protocol):
    accounts: AccountsRepository
    credentials: CredentialsRepository
    guests: GuestsRepository
    sessions: SessionsRepository
    attempts: AttemptsRepository
    access: AccessRepository
    audit: AuditRepository

    def savepoint(self) -> AbstractAsyncContextManager[None]: ...

    async def __aenter__(self) -> "AuthUnitOfWork": ...
    async def __aexit__(self, exc_type: type[BaseException] | None, exc: BaseException | None,
                        traceback: TracebackType | None) -> None: ...


class UnitOfWorkFactory(Protocol):
    def __call__(self) -> AuthUnitOfWork: ...
