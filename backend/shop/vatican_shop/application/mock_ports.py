from typing import Protocol
from uuid import UUID


class RewardBundlesGateway(Protocol):
    def get(self, bundle_id: UUID) -> dict: ...


class MockProviderGateway(Protocol):
    def lookup(self, order_id: UUID) -> str: ...


class MockEntitlementGateway(Protocol):
    def grant(self, job: dict) -> dict: ...


class MockPaymentsRepository(Protocol):
    def lock(self, key) -> None: ...
    def command(self, actor, operation, key, payload_hash) -> dict | None: ...
    def record_command(self, actor, operation, key, payload_hash, result) -> None: ...
    def product(self, identity) -> dict | None: ...
    def products(self, limit, after) -> list[dict]: ...
    def publish_product(self, snapshot, payload_hash) -> dict: ...
    def availability(self, identity, enabled) -> None: ...
    def by_key(self, account, key) -> dict | None: ...
    def order(self, identity, lock=False) -> dict | None: ...
    def units(self, identity) -> list[dict]: ...
    def create_order(self, account, key, product, payload_hash) -> dict: ...
    def provider(self, identity, lock=False) -> tuple[dict, bool]: ...
    def simulate(self, identity, scenario, unavailable) -> dict: ...
    def signal(self, identity, event_key, payload_hash) -> bool: ...
    def claim_verification(self) -> dict | None: ...
    def verification_failure(self, job, permanent=False) -> bool: ...
    def apply_verification(self, job, truth) -> bool: ...
    def claim_fulfillment(self) -> dict | None: ...
    def finish_fulfillment(self, job, receipt=None, permanent=False) -> bool: ...
    def retry_mock(self, identity, version) -> None: ...
