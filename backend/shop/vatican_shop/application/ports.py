from typing import Any, Protocol
from uuid import UUID
from .models import OfferRecord, Principal, PurchaseInspection, PurchaseRecord
from .mock_ports import MockPaymentsRepository


class AuthGateway(Protocol):
    def authenticate(self, token: str) -> Principal: ...


class WeaponDefinitionsGateway(Protocol):
    def get(self) -> list[dict]: ...


class ImageStorage(Protocol):
    def upload(self, content: bytes, content_type: str) -> dict: ...
    def require(self, key: str) -> None: ...
    def url(self, key: str) -> str: ...


class CatalogRepository(Protocol):
    def revision(self, write: bool = False) -> int: ...
    def snapshot(self) -> tuple[int, list[dict]]: ...
    def get(self, offer_id: str) -> OfferRecord | None: ...
    def list(self, limit: int, after: str | None, include_deleted: bool) -> list[OfferRecord]: ...
    def count(self) -> int: ...
    def create(self, content: dict, actor_id: UUID) -> OfferRecord: ...
    def update(self, content: dict, actor_id: UUID) -> OfferRecord: ...
    def delete(self, offer_id: str, actor_id: UUID) -> None: ...


class Repository(Protocol):
    def analytics_delivery(self,account_id,operation_id) -> dict: ...
    def claim_analytics(self) -> dict | None: ...
    def confirm_analytics(self,identity,lease,receipt) -> bool: ...
    def retry_analytics(self,identity,lease,permanent=False) -> None: ...
    def requeue_analytics(self,account_id,operation_id) -> bool: ...
    def requeue(self, account_id, operation_id, *, expected_version=None, actor_id=None, reason=None, request_key=None) -> bool: ...
    def inspect(self, account_id: UUID, operation_id: UUID) -> PurchaseInspection | None: ...
    def list_operations(self, limit, before, status, account_id) -> list[PurchaseInspection]: ...
    def events(self, account_id: UUID, operation_id: UUID, after: int, limit: int) -> list[dict]: ...
    def admin_command(self, actor_id: UUID, request_key: UUID, digest: bytes) -> dict | None: ...
    def record_admin_command(self, actor_id: UUID, request_key: UUID, digest: bytes, result: dict) -> None: ...
    def lock_player(self, account_id) -> Any: ...
    def received(self, message_id, payload_hash) -> Any: ...
    def record_message(self, message_id, payload_hash) -> Any: ...
    def operation(self, account_id: UUID, operation_id: UUID) -> PurchaseRecord | None: ...
    def history(self, account_id: UUID, limit: int, before: UUID | None) -> list[PurchaseRecord]: ...
    def counts(self, account_id) -> Any: ...
    def create(self, account_id, operation_id, offer_id, catalog_version, receipt, plan) -> Any: ...
    def claim(self) -> Any: ...
    def transition(self, job, state, receipt=None, retry=False, error_code=None) -> Any: ...


class HealthRepository(Protocol):
    def revision(self) -> str: ...


class UnitOfWork(Protocol):
    mock: MockPaymentsRepository
    catalog: CatalogRepository
    health: HealthRepository
    repository: Repository
    def __enter__(self) -> "UnitOfWork": ...
    def __exit__(self, *exception) -> Any: ...


class UnitOfWorkFactory(Protocol):
    def __call__(self) -> UnitOfWork: ...


class DefinitionsGateway(Protocol):
    def get(self) -> dict: ...


class PurchaseGateway(Protocol):
    def charge(self, job: dict) -> dict: ...
    def refund(self, job: dict) -> dict: ...
    def grant(self, job: dict) -> dict: ...


class InventoryCommandPublisher(Protocol):
    def publish(self, command: dict) -> None: ...


class AnalyticsGateway(Protocol):
    def deliver(self,message: dict) -> dict: ...
