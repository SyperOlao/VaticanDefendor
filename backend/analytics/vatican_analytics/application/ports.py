from typing import Any, Protocol
from ..domain.events import EVENT


class InboxRepository(Protocol):
    def accept(self, message_id, source_id, account_id, digest, payload, event_name=EVENT) -> dict: ...
    def get(self, source_id, event_name=EVENT) -> dict | None: ...
    def claim(self) -> dict | None: ...
    def confirm(self, source_id, lease, receipt, event_name=EVENT) -> bool: ...
    def retry(self, source_id, lease, event_name=EVENT) -> None: ...
    def requeue(self, source_id, event_name=EVENT) -> bool: ...


class HealthRepository(Protocol):
    def revision(self) -> str: ...


class UnitOfWork(Protocol):
    repository: InboxRepository
    health: HealthRepository
    def __enter__(self) -> 'UnitOfWork': ...
    def __exit__(self, *exception) -> Any: ...


class UnitOfWorkFactory(Protocol):
    def __call__(self) -> UnitOfWork: ...


class ProjectionGateway(Protocol):
    def project(self, payload: dict) -> None: ...
