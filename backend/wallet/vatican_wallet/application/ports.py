from typing import Any, Protocol
from uuid import UUID


class Repository(Protocol):
    def claim_analytics(self) -> dict | None: ...
    def confirm_analytics(self, identity, lease, receipt) -> bool: ...
    def retry_analytics(self, identity, lease, permanent=False) -> None: ...
    def requeue_analytics(self, transaction_id) -> bool: ...
    def prestige_receipt(self,purchase,account,digest) -> dict | None: ...
    def record_prestige_receipt(self,purchase,account,digest,receipt) -> None: ...
    def pay_prestige(self,account,purchase,amount) -> dict: ...
    def lock_message(self, message_id: UUID) -> None: ...
    def run_receipt(self, run_id, account_id, amount) -> dict | None: ...
    def record_run_receipt(self, run_id, account_id, amount, receipt) -> None: ...
    def history(self, account_id, currency, before, limit) -> list[dict]: ...
    def case_receipt(self, opening_id, item_index, account_id, digest) -> dict | None: ...
    def record_case_receipt(self, opening_id, item_index, account_id, digest, receipt) -> None: ...
    def pay_case(self, account_id, opening_id, currency, amount) -> dict: ...
    def award_level_currency(self, account_id, claim_id, item_index, currency, quantity, case=False) -> dict: ...
    def balances(self, account_id) -> list: ...
    def level_receipt(self, claim_id, item_index, account_id, digest) -> dict | None: ...
    def record_level_receipt(self, claim_id, item_index, account_id, digest, receipt) -> None: ...
    def command(self, account_id, operation, operation_id, digest) -> dict | None: ...
    def record_command(self, account_id, operation, operation_id, digest, result) -> None: ...
    def refundable(self, account_id, operation_id, amount) -> bool: ...
    def lock_player(self, account_id) -> Any: ...
    def received(self, message_id, payload_hash) -> Any: ...
    def record_message(self, message_id, payload_hash) -> Any: ...
    def ensure(self, account_id) -> Any: ...
    def balance(self, account_id) -> Any: ...
    def apply(self, account_id, amount, source_type, source_id) -> Any: ...


class HealthRepository(Protocol):
    def revision(self) -> str: ...


class UnitOfWork(Protocol):
    broker: "BrokerRepository"
    health: HealthRepository
    repository: Repository
    def __enter__(self) -> "UnitOfWork": ...
    def __exit__(self, *exception) -> Any: ...


class UnitOfWorkFactory(Protocol):
    def __call__(self) -> UnitOfWork: ...


class DefinitionsGateway(Protocol):
    def get(self) -> list[dict]: ...


class AnalyticsGateway(Protocol):
    def deliver(self, message: dict) -> dict: ...


from dataclasses import dataclass


@dataclass(frozen=True)
class Principal:
    account_id: UUID
    is_guest: bool


class AuthGateway(Protocol):
    def authenticate(self, token: str) -> Principal: ...

