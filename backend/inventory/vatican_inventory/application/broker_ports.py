from typing import Protocol
from uuid import UUID

from ..domain.broker import Command, CommandJob, EventJob, InspectionEntry


class BrokerRepository(Protocol):
    def accept(self, command: Command) -> bool: ...
    def reject_delivery(self, identity: UUID, body_hash: bytes, body_prefix: bytes, body_size: int,
                        code: str, message_id: UUID | None = None) -> None: ...
    def claim_command(self) -> CommandJob | None: ...
    def finish_command(self, job: CommandJob, status: str, result: dict, code: str | None = None) -> bool: ...
    def retry_command(self, job: CommandJob, code: str) -> None: ...
    def claim_event(self) -> EventJob | None: ...
    def confirm_event(self, job: EventJob) -> bool: ...
    def retry_event(self, job: EventJob) -> None: ...
    def status(self, message_id: UUID) -> dict | None: ...
    def replay_command(self, message_id: UUID) -> bool: ...
    def replay_event(self, event_id: UUID) -> bool: ...
    def inspect_page(self, kind: str, limit: int, before, state: str | None) -> list[InspectionEntry]: ...
    def inspect_detail(self, kind: str, identity: UUID) -> dict | None: ...


class BrokerPublisher(Protocol):
    def publish(self, event: EventJob) -> None: ...
