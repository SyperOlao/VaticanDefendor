from typing import Any, Protocol
from uuid import UUID
from ..domain.weapons import InventoryState, Item, Weapon, WeaponEntry
from .models import Principal
from .broker_ports import BrokerRepository


class Repository(Protocol):
    def mock_payment_receipt(self, transaction: UUID, line: int, unit: int, digest: bytes) -> dict | None: ...
    def record_mock_payment(self, transaction: UUID, line: int, unit: int, account: UUID, digest: bytes, receipt: dict) -> None: ...
    def command(self, account_id: UUID, operation: str, request_key: UUID, digest: bytes | None = None) -> dict | None: ...
    def record_command(self, account_id: UUID, operation: str, request_key: UUID, digest: bytes, receipt: dict) -> None: ...
    def purchase_result(self, account_id: UUID, operation_id: UUID) -> dict | None: ...
    def lock_message(self, message_id: UUID) -> None: ...
    def run_receipt(self, run_id: UUID, account_id: UUID, configuration_id: str, digest: bytes) -> dict | None: ...
    def record_run_receipt(self, run_id: UUID, account_id: UUID, configuration_id: str, digest: bytes, receipt: dict) -> None: ...
    def purchase_receipt(self, account_id, operation_id, configuration_id) -> dict | None: ...
    def record_purchase_receipt(self, account_id, operation_id, configuration_id, receipt) -> None: ...
    def case_receipt(self, opening_id, item_index, account_id, digest) -> dict | None: ...
    def record_case_receipt(self, opening_id, item_index, account_id, digest, receipt) -> None: ...
    def quantity(self, account_id: UUID, item_id: str) -> int: ...
    def set_quantity(self, account_id: UUID, item_id: str, quantity: int) -> None: ...
    def level_receipt(self, claim_id, item_index, account_id, digest) -> dict | None: ...
    def record_level_receipt(self, claim_id, item_index, account_id, digest, receipt) -> None: ...
    def lock_player(self, account_id) -> Any: ...
    def received(self, message_id, payload_hash) -> Any: ...
    def record_message(self, message_id, payload_hash) -> Any: ...
    def ensure(self, account_id) -> Any: ...
    def state(self, account_id: UUID) -> InventoryState: ...
    def owned(self, account_id: UUID) -> list[Weapon]: ...
    def selected(self, account_id: UUID) -> list[Weapon]: ...
    def weapon_page(self, account_id: UUID, limit: int, after, configuration_id: str | None) -> list[WeaponEntry]: ...
    def item_page(self, account_id: UUID, limit: int, after: str | None, kind: str | None) -> list[Item]: ...
    def loadout(self, account_id: UUID) -> list[UUID]: ...
    def replace_loadout(self, account_id, ids) -> Any: ...
    def grant(self, account_id, source_key, configuration_id) -> Any: ...
    def set_progress(self, instance_id: UUID, level: int, experience: int) -> None: ...
    def items(self, account_id: UUID) -> list[Item]: ...
    def item(self, account_id: UUID, item_id: str) -> Item | None: ...
    def weapon(self, account_id: UUID, instance_id: UUID) -> Weapon | None: ...


class HealthRepository(Protocol):
    def revision(self) -> str: ...


class UnitOfWork(Protocol):
    broker: BrokerRepository
    health: HealthRepository
    repository: Repository
    def __enter__(self) -> "UnitOfWork": ...
    def __exit__(self, *exception) -> Any: ...


class UnitOfWorkFactory(Protocol):
    def __call__(self) -> UnitOfWork: ...


class DefinitionsGateway(Protocol):
    def get(self) -> list[dict]: ...


class AuthGateway(Protocol):
    def authenticate(self, token: str) -> Principal: ...
