from __future__ import annotations

from typing import Any, Protocol
from uuid import UUID
from dataclasses import dataclass
from datetime import datetime
from ..domain.models import ServerSlot, RewardPolicy
from .energy_ports import EnergyRepository
from .progression_ports import ProgressionRepository
from .level_reward_ports import LevelRewardsRepository
from .case_ports import CasesRepository
from ..domain.profiles import ProfileDetails


@dataclass(frozen=True)
class Principal:
    account_id: UUID
    is_guest: bool


class AuthGateway(Protocol):
    def authenticate(self, token: str) -> Principal: ...


class InventoryGateway(Protocol):
    def snapshot(self, account_id: UUID) -> dict: ...


class InventoryCommandReader(Protocol):
    def command_status(self, message_id: UUID) -> dict | None: ...


class RewardDeliveryGateway(Protocol):
    def deliver(self, message: dict) -> dict | None | PendingDelivery: ...


@dataclass(frozen=True)
class PendingDelivery:
    """Publication was confirmed; the business result is still asynchronous."""


class RatingResultsRepository(Protocol):
    def accept(self, result) -> str | None: ...
    def quarantine(self, identity: UUID, digest: bytes, code: str) -> None: ...


class ProfileState(Protocol):
    account_id: UUID
    version: int
    display_name: str


class ProfilesRepository(Protocol):
    def ensure(self, account_id: UUID) -> ProfileState: ...
    def get(self, account_id: UUID, lock: bool = False) -> ProfileState | None: ...
    def details(self, account_id: UUID) -> ProfileDetails | None: ...
    def display_names(self, account_ids: list[UUID]) -> dict[UUID, str]: ...
    def update(self, account_id: UUID, expected_version: int, changes: dict) -> ProfileDetails | None: ...
    def bump(self, account_id: UUID) -> ProfileState: ...


class RunsRepository(Protocol):
    def audit_result_conflict(self, run, expected: bytes, received: bytes) -> None: ...
    def expired_pending(self, at: datetime, limit: int) -> list[tuple[UUID, UUID]]: ...
    def start_operation(self, account_id, request_key) -> UUID | None: ...
    def record_start(self, account_id, request_key, run_id) -> None: ...
    def server(self, server_id, lock=False) -> Any: ...
    def register_server(self, **values) -> Any: ...
    def ensure_ruleset(self, release_id) -> Any: ...
    def available_server(self,require_prestige=False) -> Any: ...
    def has_available_server(self,require_prestige=False) -> Any: ...
    def get(self, run_id, lock=False) -> Any: ...
    def active(self, account_id) -> Any: ...
    def create(self, **values) -> Any: ...
    def ready_pair(self, run_id, account_id) -> Any: ...
    def checkpoint(self, run_id, lock=False) -> Any: ...
    def save_checkpoint(self, **values) -> Any: ...
    def result(self, run_id) -> Any: ...
    def record_result(self, **values) -> Any: ...

class ContentRepository(Protocol):
    def get(self, release_id) -> Any: ...
    def publish(self, **values) -> Any: ...

class HealthRepository(Protocol):
    def schema_versions(self) -> Any: ...

class WeaponsRepository(Protocol):
    def register(self, definition) -> Any: ...
    def definitions(self) -> Any: ...

class MessagingRepository(Protocol):
    def dispatched(self, message_id: UUID, lease: UUID) -> bool: ...
    def enqueue_analytics(self, run_id: UUID, payload: dict) -> None: ...
    def analytics_delivery(self, source_id: UUID, event_name: str = 'run.analytics') -> dict: ...
    def enqueue_rating(self, run: Any, board_code: str, points: int) -> None: ...
    def rating_delivery(self, run_id: UUID) -> dict: ...
    def enqueue_case(self, opening_id: UUID, destination: str, event: str, payload: dict, item_index: int | None = None) -> UUID: ...
    def enqueue_level_reward(self, account_id: UUID, claim_id: UUID, line: Any) -> UUID: ...
    def requeue(self, message_id: UUID) -> bool: ...
    def enqueue_rewards(self, run: Any, reward: int, weapon_configuration_id: str | None = None) -> None: ...
    def reward_status(self, run_id: UUID) -> str: ...
    def claim(self) -> dict | None: ...
    def confirm(self, message_id: UUID, lease: UUID, receipt: dict | None = None) -> bool: ...
    def retry(self, message_id: UUID, lease: UUID, permanent: bool = False) -> None: ...


class UnitOfWork(Protocol):
    prestige: 'PrestigeRepository'
    local_runs: 'LocalRunsRepository'
    rating_results: RatingResultsRepository
    cases: CasesRepository
    level_rewards: LevelRewardsRepository
    progression: ProgressionRepository
    energy: EnergyRepository
    profiles: ProfilesRepository
    runs: RunsRepository
    content: ContentRepository
    health: HealthRepository
    weapons: WeaponsRepository
    messages: MessagingRepository
    def __enter__(self) -> "UnitOfWork": ...
    def __exit__(self, *exception) -> Any: ...


class UnitOfWorkFactory(Protocol):
    def __call__(self) -> UnitOfWork: ...


class GamePolicy(Protocol):
    prestige_ruleset_id: str
    rating_board_code: str
    servers: dict[UUID, ServerSlot]
    grant_ttl_seconds: int
    reward_policies: dict[str, RewardPolicy]
    energy_ruleset_id: str
    assignment_lease_seconds: int


class LocalRunsRepository(Protocol):
    def policy(self,identity: str) -> dict | None: ...
    def publish(self,policy) -> bool: ...
    def weapon_exists(self,key: str) -> bool: ...
    def start_operation(self,account: UUID,key: UUID,digest: bytes) -> UUID | None: ...
    def record_start(self,account: UUID,key: UUID,run_id: UUID,digest: bytes) -> None: ...
    def context(self,run_id: UUID) -> Any: ...
    def create_context(self,**values) -> None: ...
    def submission(self,run_id: UUID) -> Any: ...
    def record_submission(self,run,body: dict,digest: bytes,reasons: list,at: datetime) -> None: ...
    def pending(self,limit: int) -> list: ...
    def expired(self,at: datetime,limit: int) -> list: ...


class PrestigeRepository(Protocol):
    def legacy(self,account: UUID) -> list: ...
    def configuration(self,ruleset: str) -> dict | None: ...
    def publish(self,rules) -> bool: ...
    def progress(self,account: UUID,code: str) -> Any: ...
    def snapshot(self,account: UUID) -> dict: ...
    def by_request(self,account: UUID,key: UUID) -> Any: ...
    def purchase(self,account: UUID,identity: UUID) -> Any: ...
    def active(self,account: UUID) -> Any: ...
    def create(self,identity,account,key,ruleset,code,before,plan) -> Any: ...
    def payment(self,purchase) -> Any: ...
    def apply(self,account,plan,at) -> None: ...
    def refundable_purchases(self, account: UUID) -> list: ...
    def reset_by_request(self, account: UUID, key: UUID) -> Any: ...
    def reset(self, account: UUID, identity: UUID) -> Any: ...
    def active_reset(self, account: UUID) -> Any: ...
    def create_reset(self, identity, account, key, quote, purchase_ids) -> Any: ...
    def refund(self, reset) -> Any: ...
    def apply_reset(self, reset, purchases) -> None: ...
