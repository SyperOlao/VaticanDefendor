from __future__ import annotations
from dataclasses import dataclass
from datetime import datetime
from typing import Protocol
from uuid import UUID
from ..domain.cases import CaseRules


@dataclass(frozen=True)
class Opening:
    id: UUID
    account_id: UUID
    case_id: UUID
    case_code: str
    request_key: UUID
    status: str
    payment_mode: str | None
    random_seed: bytes | None
    snapshot: dict | None
    result: dict
    payment_message_id: UUID | None
    payment_receipt: dict | None
    completed_at: datetime | None


class CasesRepository(Protocol):
    def catalog(self, limit: int, offset: int) -> list[dict]: ...
    def definition(self, case_id: UUID) -> CaseRules | None: ...
    def publish(self, rules: CaseRules) -> bool: ...
    def by_request(self, account_id: UUID, key: UUID) -> Opening | None: ...
    def opening(self, account_id: UUID, opening_id: UUID) -> Opening | None: ...
    def active(self, account_id: UUID, code: str) -> bool: ...
    def create(self, opening_id: UUID, account_id: UUID, key: UUID, rules: CaseRules, mode: str, seed: bytes) -> None: ...
    def grants(self, opening_id: UUID) -> list[dict]: ...
    def pity(self, account_id: UUID, code: str) -> int: ...
    def record_draw(self, opening_id: UUID, rules: CaseRules, drop, before: int, after: int,
                    guaranteed: bool, roll: int, total: int, receipt: dict) -> None: ...
    def reject(self, opening_id: UUID, receipt: dict, at: datetime) -> None: ...
    def add_grant(self, opening_id: UUID, bundle_id: UUID, line, message_id: UUID | None,
                  receipt: dict | None, at: datetime) -> None: ...
    def finalize(self, opening_id: UUID, at: datetime) -> None: ...
