from typing import Any, Protocol
from uuid import UUID
from .models import BoardDefinition, PlayerStanding, Principal, RankedEntry
from .broker_ports import BrokerRepository


class Repository(Protocol):
    def configure_board(self, code: str) -> bool: ...
    def run_receipt(self, run_id, account_id, digest) -> dict | None: ...
    def add_run_score(self, account_id, code, points) -> dict: ...
    def record_run_receipt(self, run_id, account_id, ruleset_id, content_release_id, points, digest, receipt) -> None: ...
    def lock_player(self, account_id: UUID) -> None: ...
    def lock_message(self, message_id: UUID) -> None: ...
    def lock_run(self, run_id: UUID) -> None: ...
    def received(self, message_id, payload_hash) -> Any: ...
    def record_message(self, message_id, payload_hash) -> Any: ...
    def boards(self, limit: int, offset: int) -> list[BoardDefinition]: ...
    def ranking(self, code: str, limit: int, offset: int) -> list[RankedEntry] | None: ...
    def standing(self, code: str, account_id: UUID) -> PlayerStanding | None: ...


class HealthRepository(Protocol):
    def revision(self) -> str | None: ...


class UnitOfWork(Protocol):
    health: HealthRepository
    broker: BrokerRepository
    repository: Repository
    def __enter__(self) -> "UnitOfWork": ...
    def __exit__(self, *exception) -> Any: ...


class UnitOfWorkFactory(Protocol):
    def __call__(self) -> UnitOfWork: ...


class AuthGateway(Protocol):
    def authenticate(self, token: str) -> Principal: ...
