def boards(reference_at):
    data_note = f'Синтетика · срез {reference_at:%d.%m.%Y %H:%M} UTC · последний день неполный.'
    result = []
    for original in BOARDS:
        title, question, help_text = BOARD_TEXT[original.slug]
        rows = []
        for row in original.rows:
            charts = []
            for chart in row:
                caption, subheader, description = CAPTIONS[chart.key]
                temporal = chart.kind == 'echarts_timeseries_line'
                bar = chart.kind == 'echarts_timeseries_bar'
                units = {'runs':'Забеги, шт.', 'xp':'XP, ед.', 'level_ups':'События / уровни',
                         'level_gifts':'Подарки, шт.', 'case_openings':'Открытия, шт.',
                         'shop_purchases':'Выдачи, шт.', 'event_delivery':'События, шт.'}.get(chart.dataset,'')
                if chart.key == 'balance-daily': units = 'Убийств / забег'
                if chart.key == 'shop-spend': units = 'Престиж, ед.'
                x_title = 'День · UTC' if temporal else ('Уровень награды' if chart.key=='gifts-level' else 'Уровень церкви') if bar else ''
                charts.append(replace(chart, title=caption, subheader=subheader, description=description,
                    dimensions=DIMENSIONS.get(chart.key,chart.dimensions), x_title=x_title,
                    y_title=units if temporal or bar else '',
                    height={'bi-freshness':62, 'shop-catalog':55, 'events-contracts':55, 'cases-catalog':47}.get(chart.key,0)))
            rows.append(tuple(charts))
        footer = '**Как читать** · ' + help_text
