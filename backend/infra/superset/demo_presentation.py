def translated(expression, labels):
    def literal(value):
        return "'" + str(value).replace('\\', '\\\\').replace("'", "\\'") + "'"
    keys = ', '.join(literal(k) for k in labels)
    values = ', '.join(literal(v) for v in labels.values())
    return f"transform({expression}, [{keys}], [{values}], concat('Код: ', toString({expression})))"


